//> using dep com.lihaoyi::upickle:4.4.1

import java.nio.file.{Files, Paths}

/** Generate everyui.emoji.EmojiData from GitHub's emoji table (assets/emoji/gemoji.json, github/gemoji, MIT): every
  * emoji with its shortcodes (the names GitHub and Slack know them by), its words to search by (its tags and its
  * description) and whether it takes a skin tone, a category to a block of lines, so no string the Roku compiler is
  * given is very long.
  *
  *   scala-cli run tools/EmojiData.scala */
@main def emojiData(): Unit = {
  val table = ujson.read(Files.readString(Paths.get("assets/emoji/gemoji.json")))
  val out = Paths.get("shared/src/main/scala/everyui/emoji/EmojiData.scala")
  // each character escaped, so the source is ASCII whatever reads it
  def escaped(s: String): String = s.flatMap { c =>
    if (c == '"' || c == '\\') "\\" + c.toString
    else if (c >= 0x20 && c < 0x7f) c.toString
    else "\\u%04x".format(c.toInt)
  }
  val entries = table.arr.toVector.map { e =>
    val o = e.obj
    val words = (o("tags").arr.map(_.str) ++ o("description").str.split("[^A-Za-z0-9]+").filter(_.nonEmpty))
      .map(_.toLowerCase).distinct
    (o("category").str, o("emoji").str + "\t" + o("aliases").arr.map(_.str).mkString(",") + "\t" + words.mkString(" ") +
      "\t" + (if (o.get("skin_tones").exists(_.bool)) "1" else "0"))
  }
  val categories = entries.map(_._1).distinct
  // a category's lines, in blocks of at most 60 lines each
  val blocks = categories.map(c => c -> entries.filter(_._1 == c).map(_._2).grouped(60).toVector)
  val source = new StringBuilder
  source.append("package everyui.emoji\n\n")
  source.append("// Generated by tools/EmojiData.scala from assets/emoji/gemoji.json (github/gemoji, MIT License): do not edit.\n\n")
  source.append("/** Every emoji GitHub's table knows, a line each: the emoji, its shortcodes by commas, its words by spaces, and\n")
  source.append("  * 1 where it takes a skin tone, by tabs; in `categories`, each with its blocks of lines. */\n")
  source.append("private[emoji] object EmojiData {\n")
  source.append("  val categories: Vector[String] = Vector(" + categories.map(c => "\"" + escaped(c) + "\"").mkString(", ") + ")\n\n")
  source.append("  /** Category `i`'s lines. */\n")
  source.append("  def lines(i: Int): Vector[String] = i match {\n")
  blocks.zipWithIndex.foreach { case ((_, bs), i) =>
    source.append(s"    case $i => " + bs.indices.map(b => s"block${i}_$b").mkString(" ++ ") + "\n")
  }
  source.append("    case _ => Vector.empty\n  }\n\n")
  blocks.zipWithIndex.foreach { case ((_, bs), i) =>
    bs.zipWithIndex.foreach { case (lines, b) =>
      source.append(s"  private def block${i}_$b: Vector[String] = Vector(\n")
      source.append(lines.map(l => "    \"" + escaped(l) + "\"").mkString(",\n"))
      source.append(")\n")
    }
  }
  source.append("}\n")
  Files.createDirectories(out.getParent)
  Files.writeString(out, source.toString)
  println("wrote " + entries.size + " emoji in " + categories.size + " categories to " + out)
}
