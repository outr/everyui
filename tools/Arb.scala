//> using scala 3.10.0-RC2
//> using dep org.typelevel::fabric-io:1.30.0

import fabric.*
import fabric.io.JsonParser

import java.nio.file.{Files, Paths}

/** Generate an app's typed message accessors from its template ARB file: one `def` per message, reading
  * `everyui.i18n.Strings` (so text bound to it follows a language change), with a parameter per placeholder — an
  * `Int` where the ARB declares one, else a `String`.
  *
  *   scala-cli run tools/Arb.scala -- <template.arb> <Out.scala> <package> <Object> */
@main def arb(template: String, out: String, pkg: String, name: String): Unit = {
  val json = JsonParser(new String(Files.readAllBytes(Paths.get(template)), "UTF-8")).asObj.value
  val reserved = Set("abstract", "case", "catch", "class", "def", "do", "else", "enum", "export", "extends", "false",
    "final", "finally", "for", "given", "if", "implicit", "import", "lazy", "match", "new", "null", "object",
    "override", "package", "private", "protected", "return", "sealed", "super", "then", "this", "throw", "trait",
    "true", "try", "type", "val", "var", "while", "with", "yield")
  def ident(s: String): String = if (reserved(s) || !s.head.isLetter) "`" + s + "`" else s
  def quoted(s: String): String = "\"" + s.flatMap {
    case '"' => "\\\""
    case '\\' => "\\\\"
    case '\n' => "\\n"
    case c => c.toString
  } + "\""
  def doc(s: String): String = s.replace("*/", "* /").replace("\n", " ")

  val defs = json.toList.filterNot(_._1.startsWith("@")).collect { case (key, Str(text, _)) =>
    val placeholders = json.get("@" + key).flatMap(_.get("placeholders")).map(_.asObj.value.toList).getOrElse(Nil)
    val params = placeholders.map { case (p, meta) =>
      val kind = meta.get("type").map(_.asString).getOrElse("String")
      (p, if (kind == "int" || kind == "num" || kind == "double") "Int" else "String")
    }
    val line =
      if (params.isEmpty) s"  def ${ident(key)}: String = Strings(${quoted(key)})"
      else {
        val signature = params.map((p, t) => s"${ident(p)}: $t").mkString(", ")
        val args = params.map((p, t) => s"${quoted(p)} -> ${if (t == "Int") ident(p) + ".toString" else ident(p)}").mkString(", ")
        s"  def ${ident(key)}($signature): String = Strings.format(${quoted(key)}, $args)"
      }
    s"  /** ${doc(text)} */\n$line"
  }
  val source =
    s"""package $pkg
       |
       |import everyui.i18n.Strings
       |
       |/** The app's messages in the current language, one per key of ${Paths.get(template).getFileName}: text bound to
       |  * one follows a language change. Generated by EveryUI's tools/Arb.scala; do not edit. */
       |object $name {
       |${defs.mkString("\n")}
       |}
       |""".stripMargin
  Files.createDirectories(Paths.get(out).getParent)
  Files.write(Paths.get(out), source.getBytes("UTF-8"))
  println(s"$out: ${defs.size} messages")
}
